    { key: "inventory", label: "Ticket types & prices", permissions: %i[manage_inventory] },
    { key: "seating", label: "Seating", permissions: %i[manage_inventory] },
    { key: "contacts", label: "See attendee names & emails", permissions: %i[view_attendees],
      note: "Finance sees buyer contact in refunds and finance exports. Scanners see admission names, not email addresses." },
    { key: "attendees", label: "Guest list, waitlist & resend tickets", permissions: %i[manage_attendees] },
    { key: "door_sales", label: "Door sales", permissions: %i[box_office] },
