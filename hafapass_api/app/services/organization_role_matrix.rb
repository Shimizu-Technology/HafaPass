  def self.data
    new.data
  end

  def self.markdown
    matrix = data
    roles = matrix.fetch(:roles)
    lines = [
      "# HafaPass role matrix", "",
      "Generated by `hafapass_api/script/generate_role_matrix.rb`. Do not edit the table by hand.", "",
      "Permissions come from [OrganizationAuthorization](../hafapass_api/app/services/organization_authorization.rb); role labels and access notes come from [OrganizationRoles](../hafapass_api/app/services/organization_roles.rb). Row mappings live in [OrganizationRoleMatrix](../hafapass_api/app/services/organization_role_matrix.rb). The Settings comparison and role pickers share the [generated JSON](../hafapass_frontend/src/generated/roleMatrix.json).", "",
      "#{matrix[:notes].fetch('scope')}", "",
      "This table describes role permissions for active memberships. Event lifecycle, verification, launch capabilities, inventory and payment controls still apply. It does not grant access or override the backend checks.", "",
      "| What they can do | #{roles.map { |role| role[:label] }.join(' | ')} |",
      "|---|#{roles.map { '---|' }.join}"
    ]
    matrix[:rows].each do |row|
      lines << "| #{row[:label]} | #{roles.map { |role| row[:values].fetch(role[:key]) }.join(' | ')} |"
    end
    lines += ["", "## Access notes", ""]
    matrix[:notes].each { |key, note| lines << "- #{note}" unless key == "scope" }
    matrix[:rows].each { |row| lines << "- **#{row[:label]}:** #{row[:note]}" if row[:note] }
    lines += [
      "", "## Keeping the matrix current", "",
      "After changing authorization permissions, assignment scopes, labels or row mappings, run these commands from the repository root:", "",
      "```sh", "ruby hafapass_api/script/generate_role_matrix.rb",
      "ruby hafapass_api/script/generate_role_matrix.rb --check", "```", "",
      "The Ruby contract spec checks both generated files against the backend, including all organization and event-assignment permission grants. The focused Vitest tests check the frontend label contract, desktop and stacked mobile content, and opening/closing the comparison without changing an invite draft or a teammate's role.", "",
      "Activity categories are read from `view_activity_all`, `view_activity_events` and `view_activity_finance`. A category appears only when the backend grants it; adding those permissions requires regeneration.", ""
    ]
    lines.join("\n")
  end

  def data
    {
      roles: OrganizationRoles::LABELS.map { |key, label| { key: key, label: label } },
      # Include all source grants so freshness checks also catch permissions
      # added outside an existing row, and assignment-scope changes.
      permissions: OrganizationAuthorization::PERMISSIONS,
      event_assignment_permissions: OrganizationAuthorization::EVENT_ASSIGNMENT_PERMISSIONS,
      assignment_required_roles: OrganizationAuthorization::ASSIGNMENT_REQUIRED_ROLES,
      notes: OrganizationRoles::ROLE_MATRIX_NOTES,
      rows: ROWS.map do |row|
        row.slice(:key, :label, :note).merge(values: OrganizationRoles::LABELS.keys.to_h do |role|
          [role, value(row, role)]
        end)
      end
    }
  end

  private

  def grants?(role, *permissions)
    (permissions - OrganizationAuthorization::PERMISSIONS.fetch(role.to_sym)).empty?
  end

  def value(row, role)
    if row[:key] == "activity"
      return "All activity" if grants?(role, :view_activity_all)

      return %i[view_activity_events view_activity_finance].filter_map do |permission|
        { view_activity_events: "Events", view_activity_finance: "Money" }.fetch(permission) if grants?(role, permission)
      end.join(" & ").then { |text| text.empty? ? "No" : text }
    end

    unless grants?(role, *row.fetch(:permissions))
      if row[:key] == "contacts"
        return "Refunds & finance exports" if grants?(role, :refund, :view_finance)
        return scoped("Names only", role) if grants?(role, :scan)
      end
      return scoped("Attendee exports only", role) if row[:key] == "reports" && grants?(role, :view_attendees)

      return "No"
    end

    row[:organization_only] ? "Yes" : scoped("Yes", role)
  end

  def scoped(text, role)
    return text unless OrganizationAuthorization::ASSIGNMENT_REQUIRED_ROLES.include?(role)

    text == "Yes" ? "Assigned events" : "#{text} · assigned events"
  end
end
