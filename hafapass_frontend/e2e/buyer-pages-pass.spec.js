import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { prepare, tickets } from '../scripts/qa/buyer-pages-fixtures.mjs'

for (const width of [375, 390, 1280]) {
  test(`pending transfer confirmation escapes the mask and recovers at ${width}px`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 844 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await prepare(page)
    let pending = true
    let fail = true
    const transfer = { id: 51, recipient_email: 'friend@example.test', expires_at: '2099-11-19T08:00:00Z' }
    const json = (route, body, status = 200) => route.fulfill({ status, contentType: 'application/json', body: JSON.stringify(body) })
    await page.route('**/api/v1/me/tickets?**', route => json(route, { tickets: [{ ...tickets[0], pending_transfer: pending ? transfer : null }], meta: {} }))
    await page.route('**/api/v1/me/tickets/701/transfer', route => {
      if (fail) { fail = false; return json(route, { error: 'Please try again.' }, 503) }
      pending = false
      return json(route, {})
    })
    await page.goto('/my-tickets')
    const invoke = page.getByRole('button', { name: 'Cancel transfer', exact: true })
    await expect(page.getByText('Transfer pending', { exact: true }).locator('..')).not.toContainText('Guam time Guam time')
    await invoke.focus()
    await page.keyboard.press('Enter')
    const dialog = page.getByRole('dialog', { name: 'Cancel this transfer?', exact: true })
    await expect(dialog).toBeVisible()
    expect(await dialog.evaluate(element => element.closest('.ticket-notch'))).toBeNull()
    await expect(page.getByRole('main').getByRole('dialog')).toHaveCount(0)
    await expect(dialog.getByRole('button', { name: 'Keep transfer', exact: true })).toBeFocused()
    await page.screenshot({ path: testInfo.outputPath('transfer-dialog.png'), fullPage: true })
    const axe = await new AxeBuilder({ page }).analyze()
    expect(axe.violations).toEqual([])
    await page.keyboard.press('Shift+Tab')
    await expect(dialog.getByRole('button', { name: 'Cancel transfer', exact: true })).toBeFocused()
    await page.keyboard.press('Tab')
    await expect(dialog.getByRole('button', { name: 'Keep transfer', exact: true })).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(invoke).toBeFocused()
    await invoke.focus()
    await page.keyboard.press('Enter')
    await dialog.getByRole('button', { name: 'Cancel transfer', exact: true }).click()
    await expect(dialog.getByRole('alert')).toHaveText('Please try again.')
    await expect(dialog.getByRole('button', { name: 'Cancel transfer', exact: true })).toBeEnabled()
    await dialog.getByRole('button', { name: 'Keep transfer', exact: true }).click()
    await expect(invoke).toBeFocused()
    await invoke.focus()
    await page.keyboard.press('Enter')
    await dialog.getByRole('button', { name: 'Cancel transfer', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(page.getByText('Transfer cancelled. Your ticket stays with you.', { exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Cancel transfer', exact: true })).toHaveCount(0)
    expect(await page.evaluate(() => document.body.style.overflow)).not.toBe('hidden')
    await page.reload()
    await expect(page.getByRole('link', { name: 'Open ticket: General admission, #701', exact: true })).toBeVisible()
    await expect(page.getByText('Transfer pending', { exact: true })).toHaveCount(0)
  })

  test(`buyer account empty states lead to recovery and discovery at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: width === 1280 ? 800 : 844 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await prepare(page, { empty: true })
    await page.goto('/my-tickets')
    await expect(page.getByRole('heading', { name: 'My tickets', exact: true })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'No tickets yet', exact: true })).toBeVisible()
    await expect(page.getByText('Guest checkout? Use your order reference and checkout email.')).toBeVisible()
    await expect(page.getByText('Bought while signed in to another account? Sign in to that account to see your tickets.')).toBeVisible()
    await page.getByRole('tab', { name: 'Orders', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'No orders yet' })).toBeVisible()
    await expect(page.getByText('Guest checkout? Use your order reference and checkout email.')).toBeVisible()
    await expect(page.getByText('Bought while signed in to another account? Sign in to that account to see your tickets.')).toBeVisible()
    await page.getByRole('link', { name: 'Recover a guest order' }).click()
    await expect(page.getByLabel('Order reference')).toBeVisible()
    await expect(page.getByLabel('Email address')).toBeVisible()
    await page.goto('/my-tickets')
    await page.getByRole('link', { name: 'Browse events', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Events', exact: true })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'The first events go on sale soon.' })).toBeVisible()
    await page.goto('/saved')
    await expect(page.getByRole('heading', { name: 'Saved', exact: true })).toBeVisible()
    for (const instruction of ['Tap Save on an event to keep it here.', 'Tap Follow in an event’s organizer section to keep them here.', 'Tap Remind me on an event to get an email before it starts.']) await expect(page.getByText(instruction, { exact: true })).toBeVisible()
    const axe = await new AxeBuilder({ page }).analyze()
    expect(axe.violations).toEqual([])
    await page.getByRole('link', { name: 'Browse events', exact: true }).click()
    await expect(page).toHaveURL(/\/events$/)
  })

  test(`compact passes preserve ticket, account and tab controls at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await prepare(page)
    await page.goto('/my-tickets')
    await expect(page.getByRole('link', { name: 'Open ticket: General admission, #701', exact: true })).toBeVisible()
    await expect(page.getByText(/Guam time/).first()).toBeVisible()
    await expect(page.getByText('Used', { exact: true })).toBeVisible()
    await expect(page.getByRole('link', { name: 'Account settings and privacy' })).toHaveAttribute('href', '/account/settings')
    await page.getByText('Add HåfaPass to your phone', { exact: true }).click()
    await expect(page.getByText(/On iPhone or iPad/)).toBeVisible()
    const tickets = page.getByRole('tab', { name: 'Tickets', exact: true })
    await tickets.focus()
    await page.keyboard.press('ArrowRight')
    await expect(page.getByRole('tab', { name: 'Orders', exact: true })).toBeFocused()
    await expect(page).toHaveURL(/tab=orders/)
    await expect(page.getByText('Order HP-QA601')).toBeVisible()
    await page.reload()
    await expect(page.getByRole('tab', { name: 'Orders', exact: true })).toHaveAttribute('aria-selected', 'true')
    await page.getByRole('tab', { name: 'Orders', exact: true }).focus()
    await page.keyboard.press('ArrowLeft')
    await expect(tickets).toBeFocused()
    const open = page.getByRole('link', { name: 'Open ticket: General admission, #701', exact: true })
    await open.focus()
    await expect(open).toHaveCSS('outline-style', 'solid')
    expect((await open.boundingBox()).height).toBeGreaterThanOrEqual(44)
    await page.keyboard.press('Enter')
    await expect(page).toHaveURL(/\/tickets\/display-qa$/)
    await expect(page.getByRole('img', { name: 'Ticket entry QR code' })).toBeVisible()
  })

  test(`title band header and browser color follow scrolling at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await prepare(page)
    for (const path of ['/events', '/discover', '/collections/this-weekend', '/my-tickets', '/saved']) {
      await page.goto(path)
      await expect(page.locator('main h1')).toBeVisible()
      if (path === '/collections/this-weekend') await expect(page.getByRole('heading', { name: 'This weekend', exact: true })).toBeVisible()
      if (path === '/events' || path === '/collections/this-weekend') {
        await page.locator('.event-card').first().waitFor()
        await expect(page.getByRole('heading', { name: 'Event results', level: 2, exact: true })).toHaveCount(1)
        const headings = await new AxeBuilder({ page }).withRules(['heading-order']).analyze()
        expect(headings.violations).toEqual([])
      }
      await expect(page.locator('header')).toHaveCSS('background-color', 'rgb(3, 40, 39)')
      await expect(page.locator('meta[name="theme-color"]')).toHaveAttribute('content', '#032827')
      await page.evaluate(() => window.scrollTo(0, 300))
      await expect(page.locator('header')).toHaveCSS('background-color', 'rgb(255, 255, 255)')
      await expect(page.locator('meta[name="theme-color"]')).toHaveAttribute('content', '#ffffff')
      await page.evaluate(() => window.scrollTo(0, 0))
      await expect(page.locator('header')).toHaveCSS('background-color', 'rgb(3, 40, 39)')
    }
  })
}
